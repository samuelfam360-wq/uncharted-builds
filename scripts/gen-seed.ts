// Writes the Floor 1 seed migration from the TypeScript skill and item data.
// Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { MASTERY_SKILLS } from "../src/lib/game/data/mastery-skills";
import { STARTER_SKILLS } from "../src/lib/game/data/skills";
import type { SkillDefinition } from "../src/lib/game/types";
import { UNIQUE_ITEMS } from "../src/lib/game/data/world";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

// Insert parents before skills that evolve from them.
function depth(id: string): number {
  const s = STARTER_SKILLS.find((x) => x.id === id);
  return s?.evolvesFrom ? 1 + depth(s.evolvesFrom) : 0;
}
const ordered = [...STARTER_SKILLS].sort((a, b) => depth(a.id) - depth(b.id));

function skillRows(list: SkillDefinition[]) {
  return list
    .map(
      (s) =>
        `  (${q(s.id)}, ${q(s.name)}, ${q(s.description)}, ${q(s.kind)}, ${s.hidden}, ${json(s.conditions)}, ${json(s.effect)}, ${arr(
          s.locks,
        )}, ${s.limit ?? "null"}, ${q(s.evolvesFrom)}, ${arr(s.excludes)}, ${s.usesPerBattle ?? "null"}, ${q(s.rumor)}, ${s.enabled})`,
    )
    .join(",\n");
}
const insertSkills = `insert into public.skill_definitions
  (id, name, description, kind, hidden, conditions, effect, locks, owner_limit, evolves_from, excludes, uses_per_battle, rumor, enabled)
values
`;

let sql = `-- Generated by scripts/gen-seed.ts. Floor 1 starter skills and unique item.
-- "on conflict do nothing" keeps any edits made later on the admin page.

insert into public.skill_definitions
  (id, name, description, kind, hidden, conditions, effect, locks, owner_limit, evolves_from, excludes, uses_per_battle, rumor, enabled)
values
`;
sql += skillRows(ordered);
sql += `\non conflict (id) do nothing;\n\n`;
sql += `insert into public.unique_items (id, name, description, stat_bonus, attached_skills)\nvalues\n`;
sql += Object.values(UNIQUE_ITEMS)
  .map((u) => `  (${q(u.id)}, ${q(u.name)}, ${q(u.description)}, ${json(u.statBonus)}, ${arr([...u.attachedSkills])})`)
  .join(",\n");
sql += `\non conflict (id) do nothing;\n`;

writeFileSync(new URL("../supabase/migrations/20261109000002_seed_floor1.sql", import.meta.url), sql);
// Mastery skills: one migration per batch, so files already applied never change.
const BATCHES: { file: string; title: string; ids: string[] }[] = [
  {
    file: "20261111000001_mastery_skills.sql",
    title: "Hidden mastery skills (Sword, Shield, multi-mastery)",
    ids: ["blade_read", "hundred_cuts", "duelists_oath", "broken_blade", "parry_emperor", "retribution", "titans_defiance", "iron_riposte", "vengeance_vault", "eye_of_the_storm", "wanderers_path", "adaptive_body"],
  },
  {
    file: "20261111000002_mastery_skills_2.sql",
    title: "Hidden mastery skills (Dagger, Hammer, Fists, Gun, Bow)",
    ids: ["silent_finish", "phantom_legion", "thousand_needles", "shadow_walk", "phantom_verdict", "armor_crusher", "quake_slam", "ringing_blow", "full_swing", "anvil_breaker", "seven_strikes", "breath_control", "empty_vessel", "pressure_point", "heavenly_palm", "quick_draw", "dead_mans_hand", "final_round", "ricochet", "high_noon", "hawk_line", "marked_prey", "bending_shot", "last_arrow", "heavens_draw"],
  },
  {
    file: "20261111000003_mastery_skills_3.sql",
    title: "Hidden mastery skills (Staff, Holy, Lance)",
    ids: ["storm_sovereign", "spell_thief", "chain_catastrophe", "blood_sorcery", "star_fall", "grace_rebound", "divine_blessing", "soul_drain", "purify", "judgment_of_mercy", "curse_ward", "hallowed_soul", "comet_charge", "skewer", "iron_momentum", "sky_lance", "dragonpiercer"],
  },
];
const batched = new Set(BATCHES.flatMap((b) => b.ids));
const rest = MASTERY_SKILLS.filter((s) => !batched.has(s.id)).map((s) => s.id);
BATCHES.push({ file: "20261111000004_combo_skills.sql", title: "Combo skills (Spellblade, Iron Sanctuary, Life Palm)", ids: ["spellblade", "iron_sanctuary", "life_palm"] });
const rest2 = rest.filter((id) => !["spellblade", "iron_sanctuary", "life_palm"].includes(id));
if (rest2.length) BATCHES.push({ file: "20261112000002_newbie_skills.sql", title: "Skills for those who keep falling (Green Slime's Mercy, Horn Rabbit Weapons, Poison Toad Armour, Wolf's Scars)", ids: rest2 });
for (const b of BATCHES) {
  let out = `-- Generated by scripts/gen-seed.ts. ${b.title}.
-- "on conflict do nothing" keeps any edits made later on the admin page.

${insertSkills}`;
  out += skillRows(b.ids.map((id) => MASTERY_SKILLS.find((s) => s.id === id)!));
  out += `\non conflict (id) do nothing;\n`;
  writeFileSync(new URL(`../supabase/migrations/${b.file}`, import.meta.url), out);
}

console.log(`Wrote ${ordered.length} starter skills, ${MASTERY_SKILLS.length} mastery skills and ${Object.keys(UNIQUE_ITEMS).length} unique item(s).`);
