// Writes the Floor 1 seed migration from the TypeScript skill and item data.
// Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { MASTERY_SKILLS } from "../src/lib/game/data/mastery-skills";
import { STARTER_SKILLS } from "../src/lib/game/data/skills";
import type { SkillDefinition } from "../src/lib/game/types";
import { UNIQUE_ITEMS } from "../src/lib/game/data/world";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

// Insert parents before skills that evolve from them.
function depth(id: string): number {
  const s = STARTER_SKILLS.find((x) => x.id === id);
  return s?.evolvesFrom ? 1 + depth(s.evolvesFrom) : 0;
}
const ordered = [...STARTER_SKILLS].sort((a, b) => depth(a.id) - depth(b.id));

function skillRows(list: SkillDefinition[]) {
  return list
    .map(
      (s) =>
        `  (${q(s.id)}, ${q(s.name)}, ${q(s.description)}, ${q(s.kind)}, ${s.hidden}, ${json(s.conditions)}, ${json(s.effect)}, ${arr(
          s.locks,
        )}, ${s.limit ?? "null"}, ${q(s.evolvesFrom)}, ${arr(s.excludes)}, ${s.usesPerBattle ?? "null"}, ${q(s.rumor)}, ${s.enabled})`,
    )
    .join(",\n");
}
const insertSkills = `insert into public.skill_definitions
  (id, name, description, kind, hidden, conditions, effect, locks, owner_limit, evolves_from, excludes, uses_per_battle, rumor, enabled)
values
`;

let sql = `-- Generated by scripts/gen-seed.ts. Floor 1 starter skills and unique item.
-- "on conflict do nothing" keeps any edits made later on the admin page.

insert into public.skill_definitions
  (id, name, description, kind, hidden, conditions, effect, locks, owner_limit, evolves_from, excludes, uses_per_battle, rumor, enabled)
values
`;
sql += skillRows(ordered);
sql += `\non conflict (id) do nothing;\n\n`;
sql += `insert into public.unique_items (id, name, description, stat_bonus, attached_skills)\nvalues\n`;
sql += Object.values(UNIQUE_ITEMS)
  .map((u) => `  (${q(u.id)}, ${q(u.name)}, ${q(u.description)}, ${json(u.statBonus)}, ${arr([...u.attachedSkills])})`)
  .join(",\n");
sql += `\non conflict (id) do nothing;\n`;

writeFileSync(new URL("../supabase/migrations/20261109000002_seed_floor1.sql", import.meta.url), sql);
// Mastery skills: a migration of their own so the Floor 1 seed stays as it was applied.
let mastery = `-- Generated by scripts/gen-seed.ts. Hidden mastery skills (Sword, Shield, multi-mastery).
-- "on conflict do nothing" keeps any edits made later on the admin page.

${insertSkills}`;
mastery += skillRows(MASTERY_SKILLS);
mastery += `\non conflict (id) do nothing;\n`;
writeFileSync(new URL("../supabase/migrations/20261111000001_mastery_skills.sql", import.meta.url), mastery);

console.log(`Wrote ${ordered.length} starter skills, ${MASTERY_SKILLS.length} mastery skills and ${Object.keys(UNIQUE_ITEMS).length} unique item(s).`);
